const cache = new Map<string, string>()

/** 小程序里没有 btoa，这里用 ASCII 安全的 base64 编码（SVG 内容全为 ASCII） */
function toBase64(input: string): string {
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
  let out = ''
  for (let i = 0; i < input.length; i += 3) {
    const a = input.charCodeAt(i)
    const b = input.charCodeAt(i + 1)
    const c = input.charCodeAt(i + 2)
    const hasB = i + 1 < input.length
    const hasC = i + 2 < input.length

    out += chars[a >> 2]
    out += chars[((a & 3) << 4) | (hasB ? b >> 4 : 0)]
    out += hasB ? chars[((b & 15) << 2) | (hasC ? c >> 6 : 0)] : '='
    out += hasC ? chars[c & 63] : '='
  }
  return out
}

/**
 * 生成可直接给 <image src> 用的图标地址
 * @param name 图标名
 * @param color 颜色（必须是具体色值，不支持 currentColor）
 * @param stroke 线宽
 */
export function iconSrc(name: string, color = '#09090B', stroke = 1.75): string {
  const key = `${name}|${color}|${stroke}`
  const hit = cache.get(key)
  if (hit) return hit

  const body = PATHS[name] ?? PATHS['circle-help']
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" ` +
    `stroke="${color}" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round">` +
    `${body}</svg>`

  const src = `data:image/svg+xml;base64,${toBase64(svg)}`
  cache.set(key, src)
  return src
}

export function hasIcon(name: string): boolean {
  return name in PATHS
}
